alter table public.customers alter column name drop not null;
alter table public.customers add column if not exists customer_number bigint generated by default as identity (start with 1001);
create unique index if not exists customers_number_idx on public.customers (customer_number);

alter table public.orders add column if not exists code text;
alter table public.orders add column if not exists code_unused boolean not null default false;

create or replace function public.protect_customer_flags()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  new.customer_number := old.customer_number;
  if not public.is_admin() then
    new.blocked := old.blocked;
  end if;
  return new;
end;
$$;

create or replace function public.email_registered(check_email text)
returns boolean
language sql
stable
security definer
set search_path = public, auth
as $$
  select exists (select 1 from auth.users where lower(email) = lower(trim(check_email)));
$$;

revoke all on function public.email_registered(text) from public;
grant execute on function public.email_registered(text) to anon, authenticated;

create or replace function public.delete_customer(target uuid)
returns void
language plpgsql
security definer
set search_path = public, auth
as $$
begin
  if not public.is_admin() then
    raise exception 'Only admins can delete customers';
  end if;
  if exists (select 1 from public.admins where user_id = target) then
    raise exception 'Admin accounts cannot be deleted here';
  end if;
  delete from auth.users where id = target;
end;
$$;

revoke all on function public.delete_customer(uuid) from public, anon;
grant execute on function public.delete_customer(uuid) to authenticated;
